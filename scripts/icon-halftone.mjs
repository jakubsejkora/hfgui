/**
 * Generates build/icon.svg — "Quantized": a model as a sphere of weights, drawn
 * as a halftone with exactly four dot sizes (2-bit). One weight runs hot, in
 * signal red. Then render it: `npm run icon`.
 *
 *   node scripts/icon-halftone.mjs [out.svg]
 */
import { writeFileSync } from 'fs'

const R = 470, cx = 600, cy = 610, pitch = 46
const light = [-0.6, -0.6, 0.53]
const len = Math.hypot(...light)
const L = light.map((v) => v / len)
const rowH = (pitch * Math.sqrt(3)) / 2
const dots = []
for (let r = -Math.ceil(R / rowH) - 1; r <= Math.ceil(R / rowH) + 1; r++) {
  const y = cy + r * rowH
  const off = (r & 1) * (pitch / 2)
  for (let c = -Math.ceil(R / pitch) - 1; c <= Math.ceil(R / pitch) + 1; c++) {
    const x = cx + c * pitch + off
    const dx = (x - cx) / R, dy = (y - cy) / R
    const d = Math.hypot(dx, dy)
    if (d > 1) continue
    const nz = Math.sqrt(1 - d * d)
    const I = 0.06 + 0.94 * Math.max(0, dx * L[0] + dy * L[1] + nz * L[2])
    const level = Math.min(3, Math.floor(I * 4))
    const rim = Math.min(1, ((1 - d) * R) / (pitch * 0.55))
    const radius = (pitch / 2) * (0.14 + 0.82 * Math.sqrt(level / 3)) * Math.max(0.25, rim)
    // Only dots the tile actually shows (the sphere bleeds off two edges).
    if (x + radius < 100 || y + radius < 100 || x - radius > 924 || y - radius > 924) continue
    dots.push({ x, y, radius, I })
  }
}
// The hot weight: a full-size dot near the visual centre of the lit field — the
// same size as its neighbours, so colour alone marks it. (At the highlight on
// the rim, or ringed by a cleared halo, it read as an eye: a creature, not a
// model.)
const target = { x: cx - R * 0.27, y: cy - R * 0.27 }
const hot = dots
  .filter((d) => d.radius >= pitch * 0.47)
  .reduce((a, b) =>
    Math.hypot(b.x - target.x, b.y - target.y) < Math.hypot(a.x - target.x, a.y - target.y) ? b : a
  )
const HOT_R = hot.radius
const circles = dots
  .filter((d) => d !== hot)
  .map((d) => `<circle cx="${d.x.toFixed(1)}" cy="${d.y.toFixed(1)}" r="${d.radius.toFixed(1)}"/>`)
  .join('\n      ')

const svg = `<!--
  hfgui app icon — the source for build/icon.icns and build/icon.png.
  Generated by scripts/icon-halftone.mjs; re-render with \`npm run icon\`.

  "Quantized": a model as a sphere of weights, drawn as a halftone with exactly
  four dot sizes — 2-bit, the way quantization squeezes a model's weights into a
  few levels. One weight runs hot, in signal red, the app's one accent. The
  sphere is oversized and bleeds off the tile: scale is the statement.

  Laid out on Apple's macOS icon grid: an 824 px rounded square with 100 px of
  margin in a 1024 canvas, the margin holding the drop shadow. macOS 26 frames
  icons that stray from that shape in a grey tile, so keep the body on the grid.
-->
<svg xmlns="http://www.w3.org/2000/svg" width="1024" height="1024" viewBox="0 0 1024 1024">
  <defs>
    <clipPath id="body">
      <rect x="100" y="100" width="824" height="824" rx="185.4" />
    </clipPath>
    <linearGradient id="tile" x1="0" y1="100" x2="0" y2="924" gradientUnits="userSpaceOnUse">
      <stop offset="0" stop-color="#151517" />
      <stop offset="1" stop-color="#030303" />
    </linearGradient>
    <filter id="lift" x="-10%" y="-10%" width="120%" height="125%">
      <feDropShadow dx="0" dy="10" stdDeviation="10" flood-color="#000000" flood-opacity="0.34" />
    </filter>
  </defs>

  <g filter="url(#lift)">
    <g clip-path="url(#body)">
      <rect x="100" y="100" width="824" height="824" fill="url(#tile)" />
      <g fill="#f3f2ee">
      ${circles}
      </g>
      <circle cx="${hot.x.toFixed(1)}" cy="${hot.y.toFixed(1)}" r="${HOT_R.toFixed(1)}" fill="#ff2d1f" />
      <rect x="100" y="100" width="824" height="824" rx="185.4" fill="none" stroke="#ffffff" stroke-opacity="0.12" stroke-width="4" />
    </g>
  </g>
</svg>
`
writeFileSync(process.argv[2] ?? 'build/icon.svg', svg)
console.log(`dots: ${dots.length}, hot at (${hot.x.toFixed(0)}, ${hot.y.toFixed(0)})`)
